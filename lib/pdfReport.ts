import { jsPDF } from 'jspdf';

export interface PdfSection {
  title: string;
  lines: string[];
}

export interface PdfReportOptions {
  title: string;
  subtitle?: string;
  filename: string;
  sections: PdfSection[];
}

function wrapText(doc: jsPDF, text: string, maxWidth: number): string[] {
  return doc.splitTextToSize(text, maxWidth) as string[];
}

export function downloadReportPdf({
  title,
  subtitle,
  filename,
  sections,
}: PdfReportOptions) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48;
  const maxWidth = pageWidth - margin * 2;
  let y = margin;

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
  };

  doc.setFillColor(225, 29, 72);
  doc.rect(0, 0, pageWidth, 72, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('Rizz Assist', margin, 32);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.text(title, margin, 52);

  y = 100;
  doc.setTextColor(15, 20, 25);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(title, margin, y);
  y += 22;

  if (subtitle) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(11);
    doc.setTextColor(74, 85, 104);
    const lines = wrapText(doc, subtitle, maxWidth);
    ensureSpace(lines.length * 14 + 8);
    doc.text(lines, margin, y);
    y += lines.length * 14 + 16;
  }

  for (const section of sections) {
    if (!section.lines.length) continue;
    ensureSpace(40);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(225, 29, 72);
    doc.text(section.title, margin, y);
    y += 16;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(45, 55, 72);

    for (const line of section.lines) {
      const wrapped = wrapText(doc, `• ${line}`, maxWidth);
      ensureSpace(wrapped.length * 13 + 4);
      doc.text(wrapped, margin, y);
      y += wrapped.length * 13 + 4;
    }
    y += 10;
  }

  ensureSpace(40);
  doc.setFontSize(9);
  doc.setTextColor(160, 174, 192);
  doc.text(
    `Generated by Rizz Assist · ${new Date().toLocaleDateString()} · For fun & self-improvement`,
    margin,
    pageHeight - 28
  );

  const safeName = filename.replace(/[^a-z0-9-_]+/gi, '-').toLowerCase();
  doc.save(`${safeName}.pdf`);
}
